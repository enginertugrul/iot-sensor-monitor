CREATE TABLE sensor_rollup_checkpoints
(
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sensor_id                    BIGINT                                  NOT NULL,
    stage                        VARCHAR(30)                             NOT NULL,
    coverage_started_at          TIMESTAMPTZ                             NOT NULL,
    covered_until                TIMESTAMPTZ                             NOT NULL,
    last_attempted_bucket_start  TIMESTAMPTZ,
    last_attempted_at            TIMESTAMPTZ,
    last_successful_bucket_start TIMESTAMPTZ,
    last_successful_bucket_end   TIMESTAMPTZ,
    last_successful_at           TIMESTAMPTZ,
    last_advanced_at             TIMESTAMPTZ,
    created_at                   TIMESTAMPTZ                             NOT NULL,
    updated_at                   TIMESTAMPTZ                             NOT NULL,
    CONSTRAINT pk_sensor_rollup_checkpoints PRIMARY KEY (id),
    CONSTRAINT fk_sensor_rollup_checkpoints_sensor
        FOREIGN KEY (sensor_id)
            REFERENCES sensors (id)
            ON DELETE CASCADE,
    CONSTRAINT uk_sensor_rollup_checkpoints_sensor_stage
        UNIQUE (sensor_id, stage),
    CONSTRAINT ck_sensor_rollup_checkpoints_stage CHECK (
        stage IN ('RAW_TO_HOURLY', 'HOURLY_TO_DAILY')
        ),
    CONSTRAINT ck_sensor_rollup_checkpoints_coverage CHECK (
        coverage_started_at <= covered_until
        ),
    CONSTRAINT ck_sensor_rollup_checkpoints_raw_hour_boundaries CHECK (
        stage <> 'RAW_TO_HOURLY'
            OR (
            coverage_started_at = (
                date_trunc(
                        'hour',
                        coverage_started_at AT TIME ZONE 'UTC'
                ) AT TIME ZONE 'UTC'
                )
                AND
            covered_until = (
                date_trunc(
                        'hour',
                        covered_until AT TIME ZONE 'UTC'
                ) AT TIME ZONE 'UTC'
                )
            )
        ),
    CONSTRAINT ck_sensor_rollup_checkpoints_attempt_shape CHECK (
        (
            last_attempted_bucket_start IS NULL
                AND last_attempted_at IS NULL
            )
            OR
        (
            last_attempted_bucket_start IS NOT NULL
                AND last_attempted_at IS NOT NULL
            )
        ),
    CONSTRAINT ck_sensor_rollup_checkpoints_success_shape CHECK (
        (
            last_successful_bucket_start IS NULL
                AND last_successful_bucket_end IS NULL
                AND last_successful_at IS NULL
            )
            OR
        (
            last_successful_bucket_start IS NOT NULL
                AND last_successful_bucket_end IS NOT NULL
                AND last_successful_at IS NOT NULL
                AND last_successful_bucket_start
                < last_successful_bucket_end
                AND last_successful_bucket_start
                >= coverage_started_at
                AND last_successful_bucket_end
                <= covered_until
            )
        ),
    CONSTRAINT ck_sensor_rollup_checkpoints_timestamp_order CHECK (
        created_at <= updated_at
            AND (
            last_attempted_at IS NULL
                OR last_attempted_at BETWEEN created_at AND updated_at
            )
            AND (
            last_successful_at IS NULL
                OR last_successful_at BETWEEN created_at AND updated_at
            )
            AND (
            last_advanced_at IS NULL
                OR last_advanced_at BETWEEN created_at AND updated_at
            )
        )
);

CREATE INDEX ix_sensor_rollup_checkpoints_stage_covered_until
    ON sensor_rollup_checkpoints (stage, covered_until, sensor_id);